     public void DataTableHall() {

        AdminControler Cc = new AdminControler();
        List<Hall> list = Cc.listHalls();
        DefaultTableModel DFT = (DefaultTableModel) halltable.getModel();
        DFT.setRowCount(0);
        for (Hall k : list) {

            String id = k.getHallId();
            String hallCap = k.getHallCap();
            String pricePerDay = k.getPricePerDay(); 
            String actype = k.getAcType();
            DFT.addRow(new Object[]{ id,hallCap,pricePerDay,actype });

        }
    }


    public boolean validateSubmit() {

        boolean b = false;
        if (txtNicFD.getText().equals("")) {

            b = false;
            JOptionPane.showMessageDialog(null, "Customer NIC is requried");
            txtNicFD.requestFocus();
        } else if (txtNameFD.getText().equals("")) {

            b = false;
            JOptionPane.showMessageDialog(null, "Customer Name is requried");
            txtNameFD.requestFocus();

        } else if (txtTeleFD.getText().equals("")) {

            b = false;
            JOptionPane.showMessageDialog(null, "Customer Telephone Number is requried");
            txtTeleFD.requestFocus();

        } else if (txtEmailFD.getText().equals("")) {

            b = false;
            JOptionPane.showMessageDialog(null, "Customer Email is requried");
            txtEmailFD.requestFocus();

        } else {
            b = true;

        }

        return b;

    }


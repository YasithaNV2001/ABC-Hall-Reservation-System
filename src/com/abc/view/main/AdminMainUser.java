    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed

        if (validateSearch()) {
            search = txtSearch.getText();
            UserControler uc = new UserControler();
            Customer cust = uc.customerSearch(search);
            if (cust.getCustomerId() == null) {

                JOptionPane.showMessageDialog(null, "Enter Customer NIC is invalid");
                txtSearch.requestFocus();
            } else {

                txtNameFD.setText(cust.getName());
                txtNicFD.setText(cust.getCustomerId());
                txtTeleFD.setText(cust.getTelephoneNumber());
                txtEmailFD.setText(cust.getGmail());

                txtSearch.setText("");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Enter Customer NIC to search ");
        }


    }//GEN-LAST:event_btnSearchActionPerformed


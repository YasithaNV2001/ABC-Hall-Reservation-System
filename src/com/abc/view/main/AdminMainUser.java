    public void DataTable() {

        CustomerControler Cc = new CustomerControler();
        List<Customer> list = Cc.listCustomer();
        DefaultTableModel DFT = (DefaultTableModel) jDataTableFD.getModel();
        DFT.setRowCount(0);
        for (Customer k : list) {

            int no = k.getCustNo();
            String id = k.getCustomerId();
            String name = k.getName();
            String tele = k.getTelephoneNumber();
            String gmail = k.getGmail();
            String userT = k.getUser().getUserType().toString();
            String userID = k.getUser().getUserId();
            String date = k.getCreateDate();

            DFT.addRow(new Object[]{no, id, name, tele, gmail, userT, userID, date});

        }
    }


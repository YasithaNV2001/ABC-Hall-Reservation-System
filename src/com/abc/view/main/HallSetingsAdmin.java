    public void DataTable() {

        AdminControler Cc = new AdminControler();
        List<Hall> list = Cc.listHalls();
        DefaultTableModel DFT = (DefaultTableModel) HallTable.getModel();
        DFT.setRowCount(0);
        for (Hall k : list) {

            String id = k.getHallId();
            String halltype = k.getHallType();
            String actype = k.getAcType();
            String hallCap = k.getHallCap();
            double pricePerDay = k.getPricePerDay();
            int key = k.getHallNo();
            String State=k.getHallState();
            String inDate=k.getHallInDate();
            String outDate=k.getHallOutDate();

            DFT.addRow(new Object[]{key, id, halltype, actype, hallCap, pricePerDay,State,inDate,outDate});

        }
    }
    

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed

        if (validateSearch()) {

            search = txtSearch.getText();
            AdminControler Ac = new AdminControler();
            Hall h = Ac.searchHall(search);
            if (h.getHallId() == null) {
                JOptionPane.showMessageDialog(null, "Enter User id is invalid");
                txtSearch.requestFocus();
            } else {

                txtHallId.setText(h.getHallId());
                cmbHallType.getModel().setSelectedItem(h.getHallType());
                txtCapacity.setText(h.getHallCap());
                txtPricePerDay.setText(Double.toString(h.getPricePerDay()));
                if (h.getAcType().equals("AC")) {
                    rbAC.setSelected(true);
                } else {
                    rbNonAC.setSelected(true);
                }

                txtSearch.setText("");
            }
        } else {
            JOptionPane.showMessageDialog(null, "Enter User id to search ");
        }


    }//GEN-LAST:event_btnSearchActionPerformed

